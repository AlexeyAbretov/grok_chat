/**
 * Настройки нарезки и поиска по корпусу.
 *
 * Корпус — коллекция текстов, собранная для поиска. Модель эти файлы сама не помнит:
 * сервер находит в них куски и подкладывает в промпт. Здесь корпус — папка corpus/docs/,
 * markdown-заметки с шапкой и текстом. corpus/questions.json к корпусу не относится:
 * это проверочные вопросы, а не документы для поиска.
 *
 * RAG (retrieval-augmented generation) — ответ модели опирается на найденные
 * куски ваших документов, а не только на то, что модель помнит из обучения.
 * Цепочка такая: документ режется на чанки, по вопросу ищутся похожие чанки,
 * найденный текст дописывается в промпт, и только потом модель отвечает.
 *
 * Ищут по короткому чанку, а в промпт кладут parentText — секцию целиком.
 * Короткий кусок точнее совпадает с вопросом, а секция даёт модели соседний контекст.
 */

/**
 * Длинный абзац режется на окна этой длины, в символах.
 * Короткий абзац короче 480 символов и остаётся одним чанком.
 * Слишком большое окно смешивает разные темы, слишком маленькое теряет фразу.
 */
export const WINDOW = 480
/**
 * Соседние окна заходят друг на друга на 80 символов.
 * Фраза, которая стоит ровно на стыке двух окон, попадает в оба и не пропадает из поиска.
 */
export const OVERLAP = 80
/**
 * Reciprocal rank fusion (RRF) сливает два списка по месту, а не по сырому баллу.
 * 60 — обычная константа: места в двух списках остаются близкими,
 * и один индекс (BM25 или векторы) не задавливает другой.
 * Формула вклада места: 1 / (60 + номер места). Первое место даёт 1/61, второе 1/62.
 */
export const RRF_K = 60
/**
 * Сколько лучших чанков берём из BM25 и отдельно из векторов перед слиянием.
 * 30 — запас кандидатов: в финал попадут не только чемпионы одного способа поиска.
 */
export const CANDIDATE_POOL = 30
/**
 * Столько кандидатов после слияния отдаём реранкеру.
 * Реранкер читает вопрос и текст вместе, поэтому он точнее и дороже обычного поиска.
 * 24 — компромисс: достаточно кандидатов, но не весь корпус на каждый вопрос.
 */
export const RERANK_POOL = 24
/**
 * Столько фрагментов видит чат-модель в промпте.
 * recall@5 считает, попал ли правильный файл в эти же 5 мест.
 */
export const PASSAGE_LIMIT = 5

/**
 * Режим поиска.
 * vector — только близость смыслов (эмбеддинги).
 * bm25 — только совпадение слов.
 * hybrid — оба списка, потом слияние.
 */
export type SearchMode = 'vector' | 'bm25' | 'hybrid'

/**
 * Фильтр по шапке документа. Применяется до подсчёта близости, а не после выдачи.
 * Чанк чужого раздела не занимает место в топе и не «отбирает» его у нужного.
 */
export type SearchFilter = {
  /** Тип документа из шапки, например note. Пустое поле значит «тип не важен». */
  type?: string
  /** Раздел из шапки, например warehouse или git. */
  section?: string
  /** Брать документы с этой даты и новее. Дата в виде ГГГГ-ММ-ДД, её можно сравнивать как строку. */
  dateFrom?: string
  /** Брать документы не новее этой даты. */
  dateTo?: string
}

/**
 * Один markdown-файл корпуса после разбора шапки.
 * body — текст без шапки, по нему потом режут чанки.
 */
export type Document = {
  /** Путь файла, например corpus/docs/sku-4401.md. По нему сверяют, нашли ли нужный документ. */
  source: string
  /** Заголовок из шапки. Попадает в название чанка, если в теле нет своего заголовка. */
  title: string
  /** Поле type из шапки. Нужно фильтру «только такой тип». */
  type: string
  /** Поле date из шапки, формат ГГГГ-ММ-ДД. */
  date: string
  /** Поле section из шапки. Нужно фильтру «только этот раздел». */
  section: string
  /** Текст после закрывающей строки ---. Именно его режут на чанки. */
  body: string
}

/**
 * Кусок документа, по которому ищут.
 * text — кусок, по которому ищут: заголовок секции плюс окно текста.
 * parentText — секция вокруг него: модели часто нужен соседний абзац, не одна фраза.
 */
export type Chunk = {
  /** Уникальный id вида путь#номерСекции.номерКуска. По нему склеивают списки поиска. */
  id: string
  /** Из какого файла чанк. Ответ «нашли документ» проверяют по этому полю. */
  source: string
  /** Заголовок секции, не всего файла. В промпте человек видит, о чём кусок. */
  title: string
  /** Общий id секции. Несколько окон одной секции делят один parentId. */
  parentId: string
  /** Текст для поиска и для реранкера: короткий, поэтому совпадение точнее. */
  text: string
  /** Текст секции целиком. В промпт кладут его, а не каждое окно по отдельности. */
  parentText: string
  /** Копия type документа, чтобы фильтр не открывал файл заново. */
  type: string
  /** Копия date документа для фильтра по дате. */
  date: string
  /** Копия section документа для фильтра по разделу. */
  section: string
}

/**
 * Вопрос, для которого правильный файл известен заранее.
 * По таким вопросам считают recall: попал ли этот файл в топ-5.
 * paraphrase проверяет смысл другими словами, exact — редкий идентификатор вроде SKU или флага.
 */
export type GoldQuestion = {
  /** Текст вопроса, как его задал бы человек. */
  question: string
  /** Путь файла, который обязан найтись. Это «золотой» ответ поиска, не ответ модели. */
  document: string
  /** paraphrase — другие слова, exact — точная редкая строка вроде SKU-4401 или --no-verify. */
  kind: 'paraphrase' | 'exact'
  /** Необязательный фильтр. Поиск должен сузить корпус ещё до подсчёта баллов. */
  filter?: SearchFilter
}

/**
 * Фрагмент, который уже готов для промпта.
 * Это не чанк поиска: сюда попадает секция целиком и номер ссылки [1], [2], ...
 */
export type Passage = {
  /** Номер ссылки, с 1. Модель пишет [1], человек понимает, какой это фрагмент. */
  ref: number
  /** Файл, откуда секция. Попадает в строку источника над текстом. */
  source: string
  /** Заголовок секции для той же строки источника. */
  title: string
  /** Текст секции (parentText), который модель должна читать как данные. */
  text: string
}
